#!/usr/bin/env python3
"""Generate Compose design tokens (Kotlin) from tokens.json. Standard library only.

    python gen_compose.py tokens.json Tokens.kt [--package dev.farjad.launcher.ui.theme]

tokens.json is the source of truth. Never edit the generated file by hand:
change the JSON (replica-brand does this), re-run, then run contrast.py.
"""

import argparse
import json
import re
import sys


def camel(name):
    parts = re.split(r"[-_\s]+", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(name):
    c = camel(name)
    return c[:1].upper() + c[1:]


def argb(hex_value):
    h = hex_value.lstrip("#")
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return "Color(0xFF%s)" % h.upper()


def ms(value):
    return int(str(value).rstrip("ms"))


def public(d):
    return {k: v for k, v in d.items() if not k.startswith("_")}


def color_block(obj_name, colors):
    lines = ["object %s {" % obj_name]
    for k, v in public(colors).items():
        lines.append("    val %s = %s" % (camel(k), argb(v)))
    lines.append("}")
    return lines


def generate(t, package):
    out = [
        "// GENERATED by replica/design/gen_compose.py from replica/design/tokens.json. Do not edit.",
        "package %s" % package,
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.dp",
        "",
    ]
    col = t["color"]
    out += color_block("LightTokens", col["light"]) + [""]
    out += color_block("DarkTokens", col["dark"]) + [""]
    out += color_block("HomeTokens", col["home"]) + [""]

    out.append("data class TypeToken(val size: Float, val line: Float, val weight: FontWeight, val tracking: Float)")
    out.append("")
    out.append("object TypeTokens {")
    for k, v in t["type"].items():
        out.append(
            "    val %s = TypeToken(%sf, %sf, FontWeight(%d), %sf)"
            % (camel(k), v["size"], v["line"], v["weight"], v.get("tracking", 0))
        )
    out.append("}")
    out.append("")

    out.append("object SpaceTokens {")
    for i, v in enumerate(t["space"]):
        out.append("    val s%d = %d.dp" % (i, v))
    out.append("}")
    out.append("")

    out.append("object SizeTokens {")
    for k, v in t["size"].items():
        if isinstance(v, float) and v < 1:
            out.append("    const val %s = %sf" % (camel(k), v))
        else:
            out.append("    val %s = %d.dp" % (camel(k), v))
    out.append("}")
    out.append("")

    out.append("object RadiusTokens {")
    for k, v in t["radius"].items():
        out.append("    val %s = %d.dp" % (camel(k), v))
    out.append("}")
    out.append("")

    out.append("object ElevationTokens {")
    for k, v in public(t["elevation"]).items():
        out.append("    val %s = %d.dp" % (camel(k), v))
    out.append("}")
    out.append("")

    m = t["motion"]
    out.append("object MotionTokens {")
    for k in ("fast", "base", "slow"):
        out.append("    const val %sMs = %d" % (k, ms(m[k])))
    for k in ("spring-sheet", "spring-wave"):
        s = m[k]
        out.append("    const val %sDamping = %sf" % (camel(k), s["dampingRatio"]))
        out.append("    const val %sStiffness = %sf" % (camel(k), s["stiffness"]))
    out.append("}")
    out.append("")

    w = t["wave"]
    sc = t["scrim"]
    out.append("object WaveTokens {")
    out.append("    const val influenceLetters = %d" % w["influence-letters"])
    out.append("    const val maxScale = %sf" % w["max-scale"])
    out.append("    val maxOffset = %d.dp" % w["max-offset-dp"])
    out.append("}")
    out.append("")
    out.append("object ScrimTokens {")
    out.append("    const val homeMaxAlpha = %sf" % sc["home-max-alpha"])
    out.append("    const val sheetBackdropAlpha = %sf" % sc["sheet-backdrop-alpha"])
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tokens")
    ap.add_argument("out")
    ap.add_argument("--package", default="dev.farjad.launcher.ui.theme")
    a = ap.parse_args()
    with open(a.tokens, encoding="utf-8") as f:
        t = json.load(f)
    code = generate(t, a.package)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)
    print("wrote %s (%d lines)" % (a.out, code.count("\n") + 1))


if __name__ == "__main__":
    sys.exit(main())
